"""
services/disclaimer.py
──────────────────────
면책 고지와 AI 생성물 표기 — 백엔드가 만드는 산출물(리포트 마크다운·브리프)에 붙인다.

**프론트 사본은 `frontend/src/components/Disclaimer.tsx` 다.** 같은 문구가 두
곳에 있는 이유는 생성 주체가 둘이기 때문이다(화면은 React, 저장되는 리포트
본문은 파이썬). 한쪽만 고치면 화면과 내려받은 파일이 다른 말을 하게 되므로,
고칠 때는 반드시 둘 다 고친다. 이 문구들은 취향이 아니라 법에 걸린 문장이다:

  · 면책 — 자본시장법 제101조의3(2024.8.14 시행)이 유사투자자문업자의 표시·광고에
    넣으라고 정한 사항이 기준이다:
      1. 개별적인 투자 상담과 자금운용이 불가능하다는 사항
      2. 원금에 손실이 발생할 수 있으며 그 손실은 투자자에게 귀속된다는 사항
      3. 정식 금융투자업자가 아닌 유사투자자문업자라는 사항
    누락은 1억원 이하 과태료(제449조①34의3, 시행령 별표22 기준 6천만원)다.
    회원 화면의 산출물에도 적용되는지는 해석례가 없어 보수적으로 매 산출물 끝에 둔다.
  · AI 생성물 — 인공지능기본법 제31조 제2항(2026.1.22 시행)은 생성형 AI 의
    결과물에 그 사실을 표시하라고 한다. 표기는 **산출물의 맨 끝**에 둔다.
"""
from __future__ import annotations

# 2026-10 에 줄였다 (252자 → 116자). 예전 문구는 길었지만 제2호의 '원금 손실이
# 발생할 수 있다' 가 빠져 있었다('책임은 투자자에게' 는 귀속만 말한다).
#
# 3호('유사투자자문업자라는 사항')는 **아직 넣지 않는다.** 유사투자자문업은 '대가를
# 받고' 하는 업이라(제101조①) 무료인 지금은 유사투자자문업자가 아니고, 신고 수리
# 전에 그렇게 적으면 사실과 다른 자기 표시다. **신고가 수리되는 날(유료화 전)** 첫
# 문장을 금융위 '필수 기재사항 준수 예시'(2026.4.20) 꼴로 바꾼다 — 프론트 사본도 같이:
#   "본 서비스 운영자([상호])는 정식 금융투자업자가 아닌 유사투자자문업자로, 개별적인
#    투자 상담과 자금운용이 불가능합니다."
# '등록·인가' 같은 말은 쓰지 않는다 — 유사투자자문업은 신고제다.
#
# 뺀 것과 이유: '투자자문을 제공하지 않는다'(신고 후 유사투자자문과 모순으로 읽힘),
# '투자목적·재산상황을 반영한 개별 자문을 하지 않는다'(1호와 중복), '정확성 비보장'·
# '전적으로'(법정 사항이 아니고, 하단 고지로는 면책 효력도 약하다 — 약관규제법 제7조).
DISCLAIMER_TEXT = (
    "본 서비스 운영자는 금융투자업자가 아니며 개별적인 투자 상담과 자금운용이 불가능합니다. "
    "제공 정보는 매매 권유가 아닌 투자 참고자료이며, 투자 시 원금 손실이 발생할 수 있고 "
    "그 손실은 투자자에게 귀속됩니다."
)

# 면책 블록의 표지. 프론트가 이 문자열로 본문에서 블록을 걷어내고 자기 고지를
# 그린다(LensReport `stripAppendix`) — 바꾸면 그쪽도 같이 바꾼다.
DISCLAIMER_MARKER = "[투자 유의사항]"

# 리포트 본문 끝에 붙이는 마크다운 조각.
DISCLAIMER_MD = "\n\n---\n\n> **" + DISCLAIMER_MARKER + "** " + DISCLAIMER_TEXT + "\n"

# AI 생성물 표기. 산출물마다 **무엇이** AI 생성인지가 달라 문장을 고른다 —
# 브리프는 시세·등락 수치는 계산값이고 뉴스 요약·시장 상황만 AI 가 쓴다.
# 표지(AI_LABEL_MARKER)는 모든 문장에 들어 있어야 한다: 중복 방지와 프론트의
# '표기 누락 시 보충' 판정이 이 문자열로 한다.
AI_LABEL_MARKER = "AI 생성물"
AI_LABEL_REPORT = "※ 이 리포트는 생성형 AI가 작성한 AI 생성물입니다."
# 전날 브리핑은 본문 전체를 모델이 쓴다 (2026-10 에 '계산 사실 + AI 서술' 방식으로
# 바꿨다가 사용자 요청으로 되돌렸다). 문구도 '전체' 로 적는다.
AI_LABEL_BRIEF = "※ 이 브리핑은 생성형 AI가 작성한 AI 생성물입니다."


def append_disclaimer(markdown: str, ai_label: str | None = None) -> str:
    """마크다운 끝에 면책 고지를 붙이고, `ai_label` 이 있으면 **맨 마지막 줄**에 붙인다.

    이미 붙어 있으면 두 번 붙이지 않는다(끝 블록을 지금 문구로 바꿔 단다). 두 번
    붙는 경로가 실재한다 — 리포트는
    공용 캐시에서 되살아나고(`routers/reports.py` 의 `_cached_shared_result`),
    되살린 본문을 다시 이 함수에 통과시키는 호출부가 생기기 쉽다.
    """
    if not markdown:
        # 빈 본문에 고지만 남기지 않는다. 생성 실패를 '고지뿐인 리포트' 로
        # 위장하면 실패가 성공처럼 보인다 (§1.3).
        return markdown
    # 이미 붙었는지는 **본문 어딘가의 단어**가 아니라 **붙인 블록 그 자체**로 판단한다.
    # 예전에는 'AI 생성물' 이 본문 어디에 있든 표기를 생략했다 — 본문에는 LLM 이 쓴
    # 시장 상황·뉴스 요약이 들어 있고, 인공지능기본법 기사를 요약하면 그 단어가
    # 나온다. 그러면 맨 끝의 AI 생성물 표기가 빠진 채 나갔다.
    #
    # 끝에 이미 붙은 블록은 걷어내고 **지금 문구로** 다시 붙인다. 문구를 바꾼 뒤에도
    # 옛 블록이 남은 본문(공용 캐시에서 되살린 리포트 등)이 이 함수를 다시 지나면,
    # 옛 블록 아래에 새 블록이 하나 더 붙지 않고 새 문구 하나만 남는다.
    base, old_label = _strip_tail_appendix(markdown)
    out = base + DISCLAIMER_MD
    label = ai_label or old_label
    if label:
        out = out.rstrip() + "\n\n" + label + "\n"
    return out


def _strip_tail_appendix(markdown: str) -> tuple[str, str | None]:
    """본문 **끝**에 붙은 면책 블록과 AI 표기 줄을 걷어낸다 → (본문, 걷어낸 AI 표기).

    끝에 있을 때만 걷는다 — 본문 중간에 표지 문자열을 인용한 것은 건드리지 않는다.
    프론트 `stripAppendix` 와 같은 규칙이다.
    """
    out = markdown.rstrip()
    label = None
    lines = out.split("\n")
    if lines and lines[-1].strip().startswith("※") and AI_LABEL_MARKER in lines[-1]:
        label = lines[-1].strip()
        out = "\n".join(lines[:-1]).rstrip()
    head = "\n> **" + DISCLAIMER_MARKER + "**"
    i = out.rfind(head)
    if i >= 0 and "\n" not in out[i + 1:]:
        out = out[:i].rstrip()
        if out.endswith("---"):
            out = out[:-3].rstrip()
    return out, label
